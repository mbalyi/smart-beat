import { readFile } from "node:fs/promises";
import path from "node:path";

import AxeBuilder from "@axe-core/playwright";
import { test as base, expect, type Page } from "@playwright/test";

type MenuAction = "open" | "toggle-theme" | "shortcuts" | "licenses" | "about";

interface MixerSettings {
  version: number;
  master: number;
  tracks: { volume: number; pan: number; mute: boolean; solo: boolean }[];
}

declare global {
  interface Window {
    __emitMenuAction: (action: MenuAction) => number;
    __emitTauriEvent: (event: string, payload: unknown) => number;
    __dialogResult: string | null;
    __mixes: Map<string, MixerSettings>;
    __ipcCalls: { cmd: string; args: unknown }[];
  }
}

const TAURI_MOCK = path.join(import.meta.dirname, "tauri-mock.js");

/** Guitar Pro files the mocked Rust core can "read" (generated by scripts/make-fixtures.mjs). */
export const FIXTURES_DIR = path.join(import.meta.dirname, "fixtures");

/** A song made for the tests: 4 tracks, 60 then 120 BPM, 12 seconds long. */
export const PRACTICE_SONG = "/Users/me/Music/practice-song.gp";

export const LICENSE_TEXT = "react 19.3.0 — MIT License\n\nPermission is hereby granted…\n";

/** Serves e2e/fixtures/ at /__e2e__/files/ for the mocked `read_score_file`. */
export async function serveFixtures(page: Page) {
  await page.route("**/__e2e__/files/*", async (route) => {
    const name = decodeURIComponent(new URL(route.request().url()).pathname.split("/").pop()!);
    try {
      const body = await readFile(path.join(FIXTURES_DIR, path.basename(name)));
      await route.fulfill({ contentType: "application/octet-stream", body });
    } catch {
      await route.fulfill({ status: 404 });
    }
  });
}

export const test = base.extend<{ app: Page }>({
  app: async ({ page }, use) => {
    await page.addInitScript({ path: TAURI_MOCK });
    await serveFixtures(page);
    // The notice file is generated at package time; serve a stand-in.
    await page.route("**/third-party-licenses.txt", (route) =>
      route.fulfill({ contentType: "text/plain; charset=utf-8", body: LICENSE_TEXT }),
    );
    await page.goto("/");
    await expect(page.getByRole("heading", { level: 1 })).toBeVisible();
    await use(page);
  },
});

/** Simulates a native menu click once the UI has subscribed to menu events. */
export async function emitMenuAction(page: Page, action: MenuAction) {
  await expect
    .poll(() => page.evaluate((a) => window.__emitMenuAction(a), action))
    .toBeGreaterThan(0);
}

/** Simulates the OS dragging files onto the window and dropping them. */
export async function dropFiles(page: Page, paths: string[]) {
  const position = { x: 100, y: 100 };
  await expect
    .poll(() =>
      page.evaluate((payload) => window.__emitTauriEvent("tauri://drag-enter", payload), {
        paths,
        position,
      }),
    )
    .toBeGreaterThan(0);
  await page.evaluate((payload) => window.__emitTauriEvent("tauri://drag-drop", payload), {
    paths,
    position,
  });
}

/** Waits until the score is drawn and the instrument sounds are loaded. */
export async function waitForScore(page: Page) {
  await expect(page.locator(".at-surface svg").first()).toBeVisible({ timeout: 20_000 });
  await expect(page.getByText("Rendering score…")).toHaveCount(0, { timeout: 20_000 });
  await expect(page.getByRole("button", { name: "Play" })).toBeEnabled({ timeout: 30_000 });
}

/** Opens a song through File › Open… and the (mocked) native dialog. */
export async function openSong(page: Page, filePath = PRACTICE_SONG) {
  await page.evaluate((p) => (window.__dialogResult = p), filePath);
  await emitMenuAction(page, "open");
  await waitForScore(page);
}

/** The 0:00 / 0:12 display, as seconds played. */
export async function playedSeconds(page: Page): Promise<number> {
  const text = (await page.getByRole("timer").textContent()) ?? "";
  const [minutes, seconds] = text.split("/")[0]!.trim().split(":").map(Number);
  return minutes! * 60 + seconds!;
}

/**
 * Key that moves focus to the next control. WebKit on macOS follows the OS
 * "keyboard navigation" setting, which is off by default: plain Tab only
 * reaches text fields there, Option+Tab reaches buttons and links (as in Safari).
 */
export function tabKey(browserName: string): string {
  return browserName === "webkit" && process.platform === "darwin" ? "Alt+Tab" : "Tab";
}

/** Runs axe-core against WCAG 2.2 A/AA rules and fails on any violation. */
export async function expectNoA11yViolations(page: Page) {
  const results = await new AxeBuilder({ page })
    .withTags(["wcag2a", "wcag2aa", "wcag21a", "wcag21aa", "wcag22aa", "best-practice"])
    .analyze();
  const violations = results.violations.map(
    (v) => `${v.id}: ${v.help} → ${v.nodes.map((n) => n.target.join(" ")).join(", ")}`,
  );
  expect(violations).toEqual([]);
}

