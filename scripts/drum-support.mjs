// Writes docs/drum-midi-support.md: which drum numbers the bundled SoundFonts play
// (run with `pnpm drums:report`). Needs Node 22.18+ (runs the TypeScript sources directly).
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { DRUM_FALLBACK, DRUM_MIDI_MAP } from "../src/lib/score/drum-map.ts";
import { percussionKeys } from "../src/lib/score/sf2-keys.ts";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const fonts = [
  ["Sonivox (default)", "public/soundfont/sonivox.sf2"],
  ["FluidR3", "public/soundfont/FluidR3Mono_GM.sf3"],
].filter(([, file]) => existsSync(path.join(root, file)));

const plays = fonts.map(([name, file]) => [
  name,
  percussionKeys(new Uint8Array(readFileSync(path.join(root, file)))),
]);

const cell = (keys, key) => {
  if (keys.has(key)) return "plays";
  const fallback = DRUM_FALLBACK[key];
  if (fallback !== undefined && keys.has(fallback)) return `silent, plays ${fallback} instead`;
  return "**silent**";
};

const lines = [
  "# Drum numbers and the bundled SoundFonts",
  "",
  "Generated by `pnpm drums:report` from `src/lib/score/drum-map.ts` (the single table of drum",
  "numbers, names from Guitar Pro 8's Virtual Drumkit) and the percussion kit (bank 128) of each",
  "SoundFont. Do not edit by hand.",
  "",
  "- **plays**: the SoundFont has a sample on that key.",
  "- **silent, plays N instead**: no sample; Smart Beat plays key N (`DRUM_FALLBACK`) when it generates the MIDI. The score keeps the original number.",
  "- Whether a sample is the *right* instrument is judged by ear; this table only says which keys sound.",
  "",
  `| Number | Name | ${plays.map(([name]) => name).join(" | ")} |`,
  `| ---: | --- | ${plays.map(() => "---").join(" | ")} |`,
];
for (const key of Object.keys(DRUM_MIDI_MAP).map(Number)) {
  lines.push(
    `| ${key} | ${DRUM_MIDI_MAP[key]} | ${plays.map(([, keys]) => cell(keys, key)).join(" | ")} |`,
  );
}
lines.push(
  "",
  "## Decision",
  "",
  "Both bundled SoundFonts are General MIDI kits: they play the keys 27 to 87 and nothing above.",
  "The Guitar Pro articulations above 87 (rim shot, choked cymbals, hand percussion variants…)",
  "are mapped to the nearest General MIDI sound for now. A better drum kit or an imported kit is",
  "tracked in #40 and the audio engine spike #34.",
  "",
);
writeFileSync(path.join(root, "docs/drum-midi-support.md"), lines.join("\n"));
console.log(`Wrote docs/drum-midi-support.md (${Object.keys(DRUM_MIDI_MAP).length} numbers)`);
