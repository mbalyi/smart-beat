#!/usr/bin/env node
// Writes public/third-party-licenses.txt: the license notices of every
// open-source component shipped in the app (Rust crates + npm packages).
// Runs before every `tauri build` (see src-tauri/tauri.conf.json) and is shown
// in Help → Open-Source Licenses, which satisfies the notice obligations of
// MIT / BSD / Apache-2.0 / MPL-2.0 for binary distribution.

import { execFileSync } from "node:child_process";
import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";

import { EMBEDDED_BUILD_PACKAGES } from "./license-policy.mjs";
import {
  listProductionPackages,
  readInstalledPackage,
  readLicenseFiles,
  ROOT,
} from "./npm-packages.mjs";

const OUTPUT = path.join(ROOT, "public", "third-party-licenses.txt");
const RULE = "=".repeat(80);
const THIN_RULE = "-".repeat(80);

function rustNotices() {
  // Write to a file instead of capturing stdout: cargo-about refuses to print
  // to redirected output under PowerShell (Windows CI) to avoid encoding issues.
  const dir = mkdtempSync(path.join(tmpdir(), "smart-beat-licenses-"));
  const output = path.join(dir, "rust-notices.txt");
  try {
    execFileSync(
      "cargo",
      [
        "about",
        "generate",
        "--manifest-path",
        "src-tauri/Cargo.toml",
        "--config",
        "about.toml",
        "--output-file",
        output,
        "about.hbs",
      ],
      { cwd: ROOT, stdio: ["ignore", "inherit", "inherit"] },
    );
    return readFileSync(output, "utf8").trim();
  } catch (error) {
    throw new Error(
      "cargo about failed. Is cargo-about installed? cargo install cargo-about --locked --features cli",
      { cause: error },
    );
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
}

function npmNotices() {
  const seen = new Set();
  const packages = [
    ...listProductionPackages(),
    ...EMBEDDED_BUILD_PACKAGES.map(readInstalledPackage),
  ].filter((pkg) => !seen.has(pkg.name) && seen.add(pkg.name));

  return packages
    .map((pkg) => {
      const texts = readLicenseFiles(pkg.paths[0]);
      return [
        RULE,
        `${pkg.name} ${pkg.versions.join(", ")}`,
        `License: ${pkg.license ?? "UNKNOWN"}`,
        ...(pkg.homepage ? [`Homepage: ${pkg.homepage}`] : []),
        THIN_RULE,
        texts.length > 0
          ? texts.join(`\n\n${THIN_RULE}\n\n`)
          : `This package does not ship a license file. It is distributed under the ${pkg.license} license.`,
      ].join("\n");
    })
    .join("\n\n");
}

const document = [
  "Smart Beat — third-party software notices",
  "",
  "Smart Beat includes the open-source components listed below. Each is",
  "distributed under its own license, reproduced here as required.",
  "",
  `Generated by scripts/generate-licenses.mjs on ${new Date().toISOString().slice(0, 10)}.`,
  "",
  "",
  "RUST CRATES (application core)",
  "",
  rustNotices(),
  "",
  "",
  "JAVASCRIPT PACKAGES (user interface)",
  "",
  npmNotices(),
  "",
].join("\n");

mkdirSync(path.dirname(OUTPUT), { recursive: true });
writeFileSync(OUTPUT, document);
console.log(`✓ Wrote ${path.relative(ROOT, OUTPUT)} (${Math.round(document.length / 1024)} KiB)`);
