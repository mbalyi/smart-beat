// Pure helpers for scripts/dependency-report.mjs: parse the outputs of `pnpm outdated`,
// `cargo outdated` and the workflow files, and render the weekly issue body.

export const REPORT_MARKER = "<!-- dependency-report -->";

/** Splits "1.2.3" or "v1.2.3" into numbers; missing parts count as 0. */
function numbers(version) {
  return String(version)
    .replace(/^v/, "")
    .split(/[.+-]/)
    .slice(0, 3)
    .map((part) => Number.parseInt(part, 10) || 0);
}

/** "major", "minor" or "patch": the biggest part that differs between two versions. */
export function bumpKind(current, latest) {
  const [a, b] = [numbers(current), numbers(latest)];
  if (b[0] !== a[0]) return "major";
  if (b[1] !== a[1]) return "minor";
  return "patch";
}

/** Rows from `pnpm outdated --format json` (an object keyed by package name). */
export function parsePnpmOutdated(json) {
  return Object.entries(json ?? {})
    .filter(([, info]) => info.latest && info.current && info.latest !== info.current)
    .map(([name, info]) => ({
      name,
      current: info.current,
      latest: info.latest,
      kind: info.dependencyType ?? "dependencies",
      bump: bumpKind(info.current, info.latest),
    }))
    .sort((a, b) => a.name.localeCompare(b.name));
}

/** Rows from `cargo outdated --root-deps-only --format json`. */
export function parseCargoOutdated(json) {
  return (json?.dependencies ?? [])
    .filter((dep) => /^\d/.test(dep.latest ?? "") && dep.latest !== dep.project)
    .map((dep) => ({
      name: dep.name,
      current: dep.project,
      latest: dep.latest,
      kind: dep.kind ?? "Normal",
      bump: bumpKind(dep.project, dep.latest),
    }))
    .sort((a, b) => a.name.localeCompare(b.name));
}

/** Unique `owner/repo@ref` pairs from `uses:` lines in workflow files (local and docker uses skipped). */
export function parseActionUses(workflowTexts) {
  const found = new Map();
  for (const text of workflowTexts) {
    for (const match of text.matchAll(/^\s*-?\s*uses:\s*([\w.-]+\/[\w./-]+)@([\w.-]+)/gm)) {
      const [, action, ref] = match;
      found.set(`${action}@${ref}`, { action, ref });
    }
  }
  return [...found.values()].sort((a, b) => a.action.localeCompare(b.action));
}

/**
 * Actions whose newest release tag has a higher major than the pinned ref.
 * `latestByRepo` maps "owner/repo" to its latest release tag (missing entries are skipped).
 */
export function outdatedActions(uses, latestByRepo) {
  return uses
    .map(({ action, ref }) => {
      const repo = action.split("/").slice(0, 2).join("/");
      const latest = latestByRepo[repo];
      return { name: action, current: ref, latest, repo };
    })
    .filter(({ current, latest }) => {
      if (!latest || !/^v?\d/.test(current) || !/^v?\d/.test(latest)) return false;
      return numbers(latest)[0] > numbers(current)[0];
    })
    .map((row) => ({ ...row, kind: "action", bump: "major" }));
}

function table(rows) {
  if (rows.length === 0) return "_Nothing to update._\n";
  const lines = ["| Package | Current | Latest | Change |", "| --- | --- | --- | --- |"];
  for (const row of rows) {
    lines.push(`| \`${row.name}\` | ${row.current} | ${row.latest} | ${row.bump} |`);
  }
  return `${lines.join("\n")}\n`;
}

export function totalOutdated({ npm, cargo, actions }) {
  return npm.length + cargo.length + actions.length;
}

/** Title of the weekly issue, e.g. "Dependency updates, week of 2026-11-09". */
export function issueTitle(date) {
  return `Dependency updates, week of ${date.toISOString().slice(0, 10)}`;
}

export function renderReport({ npm, cargo, actions }, runUrl) {
  const lines = [
    REPORT_MARKER,
    "Weekly list of outdated dependencies. Dependabot does not open update pull requests for these;",
    "update what you want in one branch and one PR. Security fixes still arrive as Dependabot pull requests.",
    "",
    `## npm (${npm.length})`,
    "",
    table(npm),
    `## Cargo (${cargo.length})`,
    "",
    table(cargo),
    `## GitHub Actions (${actions.length})`,
    "",
    table(actions),
  ];
  if (runUrl) lines.push(`Generated by [this workflow run](${runUrl}).`, "");
  return lines.join("\n");
}
