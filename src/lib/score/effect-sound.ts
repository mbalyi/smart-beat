/**
 * Makes the effects alphaTab's player leaves silent audible, approximately:
 * - slap, pop and tapping are played louder (percussive, accented attacks);
 * - downstrokes a little louder than upstrokes;
 * - a closed wah quieter than an open one. alphaSynth has no filter, so the
 *   wah can only be a change of volume (MIDI Expression, which fades don't use).
 *
 * It edits the MIDI alphaTab generated, before the synthesizer loads it
 * (alphaTab's `midiLoad` event), and finds each beat's notes through the tick
 * lookup, so every repeat of a bar is covered.
 */
import { midi, model } from "@coderline/alphatab";

import { playableDrumKey } from "@/lib/score/drum-map";
import type { Beat } from "@/lib/score/model";

const { ControlChangeEvent, ControllerType, NoteOffEvent, NoteOnEvent } = midi;

/** MIDI channel 10, the percussion channel (0-based). */
const PERCUSSION_CHANNEL = 9;
const { PickStroke, TripletFeel, WahPedal } = model;

/** How much louder (MIDI velocity) each effect plays its notes. */
export const VELOCITY_CHANGE = {
  slap: 18,
  pop: 26,
  tap: 14,
  downstroke: 8,
  upstroke: -8,
} as const;

/** MIDI Expression for a closed and an open wah (or no wah). */
export const WAH_EXPRESSION = { closed: 64, open: 127 } as const;

const clampVelocity = (value: number) => Math.min(127, Math.max(1, Math.round(value)));

/** How much a beat's notes should get louder or quieter. */
function velocityChange(beat: Beat): number {
  let change = 0;
  if (beat.slap) change += VELOCITY_CHANGE.slap;
  if (beat.pop) change += VELOCITY_CHANGE.pop;
  if (beat.tap) change += VELOCITY_CHANGE.tap;
  if (beat.pickStroke === PickStroke.Down) change += VELOCITY_CHANGE.downstroke;
  if (beat.pickStroke === PickStroke.Up) change += VELOCITY_CHANGE.upstroke;
  return change;
}

/**
 * Adjusts `file` (generated by alphaTab for `score`) in place. Returns how
 * many notes got louder or quieter, and how many wah changes were added.
 */
export function approximateSilentEffects(
  file: midi.MidiFile,
  lookup: midi.MidiTickLookup,
): { notes: number; wah: number } {
  // Note-ons by track and start tick.
  const noteOns = new Map<string, midi.NoteOnEvent[]>();
  for (const track of file.tracks) {
    for (const event of track.events) {
      if (!(event instanceof NoteOnEvent)) continue;
      const key = `${event.track}:${event.tick}`;
      const list = noteOns.get(key);
      if (list) list.push(event);
      else noteOns.set(key, [event]);
    }
  }

  let notes = 0;
  let wah = 0;
  const wahState = new Map<number, number>();
  const shift = file.tickShift;

  for (const occurrence of lookup.masterBars) {
    const masterBar = occurrence.masterBar;
    const score = masterBar.score;
    for (const track of score.tracks) {
      const info = track.playbackInfo;
      const channels = [...new Set([info.primaryChannel, info.secondaryChannel])];
      for (const staff of track.staves) {
        const bar = staff.bars[masterBar.index];
        for (const voice of bar?.voices ?? []) {
          for (const beat of voice.beats) {
            if (beat.isRest) continue;
            const start = occurrence.start + beat.playbackStart + shift;

            // Wah: a volume step wherever the pedal position changes (voice 1 decides).
            if (voice.index === 0) {
              const previous = wahState.get(track.index) ?? WahPedal.None;
              if (beat.wahPedal !== previous) {
                const value =
                  beat.wahPedal === WahPedal.Closed ? WAH_EXPRESSION.closed : WAH_EXPRESSION.open;
                for (const channel of channels) {
                  const event = new ControlChangeEvent(
                    track.index,
                    start,
                    channel,
                    ControllerType.ExpressionControllerCoarse,
                    value,
                  );
                  file.addEvent(event);
                }
                wahState.set(track.index, beat.wahPedal);
                wah++;
              }
            }

            const change = velocityChange(beat);
            if (change === 0) continue;
            const keys = new Set(beat.notes.map((note) => note.calculateRealValue(false, true)));
            // Triplet feel moves the second note of a pair earlier; brushes move notes later.
            const swing = masterBar.tripletFeel !== TripletFeel.NoTripletFeel;
            const from = swing ? start - beat.playbackDuration / 2 : start;
            const to = start + beat.playbackDuration;
            for (let tick = Math.ceil(from); tick < to; tick++) {
              for (const event of noteOns.get(`${track.index}:${tick}`) ?? []) {
                if (!keys.has(event.noteKey)) continue;
                event.noteVelocity = clampVelocity(event.noteVelocity + change);
                notes++;
              }
            }
          }
        }
      }
    }
  }
  return { notes, wah };
}

/**
 * Replaces drum numbers the SoundFont has no sample for (rim shot, chokes,
 * world percussion above 87…) by the closest sound it does have, so they are
 * not silent. Edits `file` in place; returns how many notes were replaced.
 */
export function remapSilentDrums(file: midi.MidiFile): number {
  let replaced = 0;
  for (const track of file.tracks) {
    for (const event of track.events) {
      if (!(event instanceof NoteOnEvent || event instanceof NoteOffEvent)) continue;
      if (event.channel !== PERCUSSION_CHANNEL) continue;
      const key = playableDrumKey(event.noteKey);
      if (key === event.noteKey) continue;
      event.noteKey = key;
      if (event instanceof NoteOnEvent) replaced++;
    }
  }
  return replaced;
}
