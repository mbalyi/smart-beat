import { useMemo, useState } from "react";
import { CheckIcon, PencilIcon, Trash2Icon } from "lucide-react";

import { Badge } from "@/components/ui/badge";
import { Button } from "@/components/ui/button";
import {
  Dialog,
  DialogBody,
  DialogContent,
  DialogDescription,
  DialogFooter,
  DialogHeader,
  DialogTitle,
} from "@/components/ui/dialog";
import { Input } from "@/components/ui/input";
import { filterLibrary, parseTags, tagsOf } from "@/lib/audio/library";
import type { AssetKind, LibraryItem } from "@/lib/tauri";

function ItemRow({
  item,
  onRename,
  onRemove,
}: {
  item: LibraryItem;
  onRename: (id: string, name: string, tags: string[]) => void;
  onRemove: (id: string) => void;
}) {
  const [editing, setEditing] = useState(false);
  const [name, setName] = useState(item.name);
  const [tags, setTags] = useState(item.tags.join(", "));
  return (
    <li
      className="flex flex-wrap items-center gap-2 border-b py-2 last:border-b-0"
      data-testid="library-item"
    >
      {editing ? (
        <form
          className="flex flex-1 flex-wrap items-center gap-2"
          onSubmit={(event) => {
            event.preventDefault();
            if (!name.trim()) return;
            onRename(item.id, name.trim(), parseTags(tags));
            setEditing(false);
          }}
        >
          <Input
            aria-label={`Name of ${item.name}`}
            value={name}
            onChange={(e) => setName(e.target.value)}
            className="h-8 w-48"
            maxLength={200}
          />
          <Input
            aria-label={`Tags of ${item.name}`}
            value={tags}
            onChange={(e) => setTags(e.target.value)}
            placeholder="Tags, comma separated"
            className="h-8 w-48"
          />
          <Button type="submit" size="icon-sm" aria-label="Save the name and tags">
            <CheckIcon />
          </Button>
        </form>
      ) : (
        <>
          <div className="min-w-0 flex-1">
            <p className="truncate text-sm font-medium">{item.name}</p>
            <p className="truncate text-xs text-muted-foreground">
              {item.builtin ? "Built in, generated by Smart Beat" : `Imported from ${item.source}`}
              {item.sampleRate > 0 && ` · ${item.sampleRate / 1000} kHz`}
              {item.includesCab && " · includes a cabinet"}
            </p>
            {item.note && <p className="text-xs text-amber-700 dark:text-amber-400">{item.note}</p>}
          </div>
          {item.tags.map((tag) => (
            <Badge key={tag} variant="secondary">
              {tag}
            </Badge>
          ))}
          {!item.builtin && (
            <>
              <Button
                variant="ghost"
                size="icon-xs"
                aria-label={`Rename ${item.name}`}
                onClick={() => setEditing(true)}
              >
                <PencilIcon />
              </Button>
              <Button
                variant="ghost"
                size="icon-xs"
                aria-label={`Remove ${item.name}`}
                onClick={() => onRemove(item.id)}
              >
                <Trash2Icon />
              </Button>
            </>
          )}
        </>
      )}
    </li>
  );
}

const SECTIONS: { kind: AssetKind; title: string; help: string }[] = [
  {
    kind: "amp",
    title: "Amps and pedals",
    help: "Neural Amp Modeler captures (.nam), for example from TONE3000. Check each capture's licence before you share songs that need it.",
  },
  {
    kind: "cab",
    title: "Cabinets",
    help: "Impulse responses (.wav). Stereo files are mixed to mono; only the first 1.4 s (at 48 kHz) of a long one is used.",
  },
];

/**
 * The user's sound library: imported amp and pedal captures and cabinet IRs.
 * Files are copied into the app's own folder and never leave this computer.
 */
export function SoundLibraryDialog({
  open,
  onOpenChange,
  items,
  onImport,
  onRename,
  onRemove,
}: {
  open: boolean;
  onOpenChange: (open: boolean) => void;
  items: LibraryItem[];
  onImport: (kind: AssetKind) => void;
  onRename: (id: string, name: string, tags: string[]) => void;
  onRemove: (id: string) => void;
}) {
  const [search, setSearch] = useState("");
  const [tag, setTag] = useState<string | null>(null);
  const tags = useMemo(() => tagsOf(items), [items]);
  // A tag that no longer exists (renamed, removed) stops filtering.
  const activeTag = tag && tags.includes(tag) ? tag : null;
  const shown = useMemo(
    () => filterLibrary(items, { search, tag: activeTag }),
    [items, search, activeTag],
  );
  const filtering = search.trim() !== "" || activeTag !== null;
  return (
    <Dialog open={open} onOpenChange={onOpenChange}>
      <DialogContent size="xl">
        <DialogHeader>
          <DialogTitle>Sound library</DialogTitle>
          <DialogDescription>
            Your own amp captures and cabinets. Imported files stay on this computer; they are never
            bundled with the app or uploaded. You can also drop a .nam or .wav file on this window.
          </DialogDescription>
        </DialogHeader>
        <DialogBody>
          <div className="flex flex-wrap items-center gap-2">
            <Input
              type="search"
              aria-label="Search the library"
              placeholder="Search by name, tag or file…"
              value={search}
              onChange={(e) => setSearch(e.target.value)}
              className="h-8 w-64"
            />
            {tags.length > 0 && (
              <div role="group" aria-label="Filter by tag" className="flex flex-wrap gap-1">
                {tags.map((t) => (
                  <Button
                    key={t}
                    size="xs"
                    variant={t === activeTag ? "default" : "outline"}
                    aria-pressed={t === activeTag}
                    onClick={() => setTag(t === activeTag ? null : t)}
                  >
                    {t}
                  </Button>
                ))}
              </div>
            )}
          </div>
          {SECTIONS.map((section) => {
            const own = shown.filter((item) => item.kind === section.kind);
            return (
              <section
                key={section.kind}
                aria-label={section.title}
                className="flex flex-col gap-2"
              >
                <div className="flex items-center justify-between gap-2">
                  <h3 className="text-xs font-semibold tracking-wide uppercase">{section.title}</h3>
                  <Button size="sm" variant="outline" onClick={() => onImport(section.kind)}>
                    Import {section.kind === "amp" ? ".nam" : ".wav"}…
                  </Button>
                </div>
                <p className="text-xs text-muted-foreground">{section.help}</p>
                {own.length === 0 ? (
                  <p className="rounded-md border border-dashed px-3 py-4 text-center text-sm text-muted-foreground">
                    {filtering ? "Nothing matches." : "Nothing imported yet."}
                  </p>
                ) : (
                  <ul className="rounded-md border px-3">
                    {own.map((item) => (
                      <ItemRow key={item.id} item={item} onRename={onRename} onRemove={onRemove} />
                    ))}
                  </ul>
                )}
              </section>
            );
          })}
        </DialogBody>
        <DialogFooter>
          <Button onClick={() => onOpenChange(false)}>Done</Button>
        </DialogFooter>
      </DialogContent>
    </Dialog>
  );
}
